#!/usr/bin/env python3
"""Generate the OLED Chinese font: only the characters the firmware actually draws.

The OLED uses u8g2. Its bundled CJK fonts are Simplified Chinese, so this builds a
custom font from efont "b12" (12 px, Unicode, includes Traditional Chinese; BDF in
the u8g2 submodule, tools/font/bdf/b12.bdf, (c) The Electronic Font Open Laboratory,
BSD-style licence — u8g2 ships fonts made from the same file).

Every Chinese string the OLED shows is written as ZH("...") in the C sources
(ZH() expands to the string itself, see display_svc.c). This script collects those
strings, adds printable ASCII, and runs u8g2's bdfconv to write
components/drivers/oled_font_zh12.c. Re-run it after adding or changing a ZH() string;
a character missing from the font is drawn as nothing at all.

    python firmware/tools/gen_oled_font.py           (from the repo root)

bdfconv is compiled from the u8g2 submodule into firmware/build/bdfconv/ on first
use; set GCC=<path to gcc> if gcc is not on PATH.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
U8G2 = os.path.join(FW, "components", "u8g2")
BDF = os.path.join(U8G2, "tools", "font", "bdf", "b12.bdf")
BDFCONV_SRC = os.path.join(U8G2, "tools", "font", "bdfconv")
BUILD = os.path.join(FW, "build", "bdfconv")
OUT = os.path.join(FW, "components", "drivers", "oled_font_zh12.c")
FONT_NAME = "u8g2_font_tes_zh12"
SCAN_DIRS = [os.path.join(FW, "components", "services"), os.path.join(FW, "main")]

ZH_RE = re.compile(r'ZH\("((?:[^"\\]|\\.)*)"\)')


def bdfconv_exe():
    exe = os.path.join(BUILD, "bdfconv.exe" if os.name == "nt" else "bdfconv")
    if os.path.exists(exe):
        return exe
    os.makedirs(BUILD, exist_ok=True)
    gcc = os.environ.get("GCC", "gcc")
    srcs = [os.path.join(BDFCONV_SRC, f) for f in sorted(os.listdir(BDFCONV_SRC)) if f.endswith(".c")]
    subprocess.run([gcc, "-O2", "-w", "-o", exe] + srcs, check=True)
    return exe


def collect():
    chars = set()
    hits = 0
    for d in SCAN_DIRS:
        for root, _, files in os.walk(d):
            for f in files:
                if not f.endswith((".c", ".h")):
                    continue
                with open(os.path.join(root, f), encoding="utf-8-sig") as fh:
                    for m in ZH_RE.finditer(fh.read()):
                        hits += 1
                        chars.update(c for c in m.group(1) if ord(c) > 126)
    return sorted(chars), hits


def main():
    chars, hits = collect()
    if not chars:
        sys.exit("no ZH(\"...\") strings found")
    # 32-126 = printable ASCII (half width in efont); then every non-ASCII character used
    cmap = "32-126," + ",".join(str(ord(c)) for c in chars)
    tmp = OUT + ".tmp"
    subprocess.run([bdfconv_exe(), "-f", "1", "-m", cmap, "-n", FONT_NAME, "-o", tmp, BDF], check=True)
    with open(tmp, encoding="utf-8") as fh:
        body = fh.read()
    os.remove(tmp)
    header = (
        "// Generated by firmware/tools/gen_oled_font.py — do not edit; re-run the script.\n"
        "// efont b12 (12 px, (c) The Electronic Font Open Laboratory, BSD-style licence),\n"
        f"// printable ASCII + the {len(chars)} characters used in ZH(\"...\") strings:\n"
        f"// {''.join(chars)}\n"
        '#include "u8g2.h"\n\n'
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header + body)
    print(f"{len(chars)} characters from {hits} strings -> {os.path.relpath(OUT, FW)}")


if __name__ == "__main__":
    main()
